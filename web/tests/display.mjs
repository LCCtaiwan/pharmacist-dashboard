import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const context = { window: { APP_CONFIG: {} }, document: { addEventListener() {} }, Date, Intl, URL, setTimeout, clearTimeout };
vm.createContext(context);
vm.runInContext(app.replace(/\}\)\(\);\s*$/, 'window.test = {courseCard, courseEnd, isClosingSoon, isLimited, formatTimeRange, safeUrl, renderHeader, renderSources, state, elements, loadPayload};})();'), context);
const t = context.window.test;
const course = {title: '<script>bad</script>', rareStatus:'候選', startAt: '2099-01-01T09:00:00+08:00', endAt:'2099-01-02T17:00:00+08:00', sourceUrl:'javascript:alert(1)', registrationUrl:'https://example.org/register'};
assert.equal(t.formatTimeRange({startAt:'2099-01-01T00:00:00+08:00',datePrecision:'date'}), '時間未提供');
assert.equal(t.courseEnd({startAt:'2099-01-01T00:00:00+08:00',datePrecision:'date'}).toISOString(), '2099-01-01T15:59:59.999Z');
assert.equal(t.courseEnd({startAt:'2099-01-01T00:00:00+08:00',endAt:'2099-01-02T00:00:00+08:00',datePrecision:'date'}).toISOString(), '2099-01-02T15:59:59.999Z');
assert.equal(t.courseEnd({startAt:'2099-01-01T00:00:00+08:00',datePrecision:'time'}).toISOString(), '2098-12-31T16:00:00.000Z');
assert.equal(t.formatTimeRange({startAt:'2099-01-01T00:00:00+08:00',datePrecision:'time'}), '00:00');
assert.match(t.formatTimeRange({...course,datePrecision:'date'}), /至 2099\/01\/02｜時間未提供/);
const html = t.courseCard(course);
assert.match(html, /2099\/01\/01/);
assert.match(html, /2099\/01\/02/);
assert.match(html, /認證狀態 <strong>未確認/);
assert.match(html, /積分 <strong>未確認/);
assert.match(html, /欄位待確認/);
assert.match(html, /&lt;script&gt;bad/);
assert.ok(!html.includes('href="javascript:'));
assert.match(html, /href="https:\/\/example.org\/register"/);
assert.equal(t.safeUrl('data:text/html,bad'), '');
const deadline = new Date(Date.now()+86400000).toISOString();
assert.equal(t.isClosingSoon({registrationDeadline:deadline}), false);
assert.equal(t.isClosingSoon({registrationDeadline:deadline, registrationStatus:'報名中'}), true);
assert.equal(t.isLimited({seatsRemaining:3}), false);
assert.equal(t.isLimited({seatsRemaining:3,registrationStatus:'報名中',registrationDeadline:'2000-01-01T00:00:00Z'}), false);
assert.equal(t.isLimited({seatsRemaining:3, registrationStatus:'報名中'}), true);
for(const key of ['pageTitle','rareDefinition','dataStatus','lastUpdated','dataWarning','sourceRows']) t.elements[key] = {};
t.state.payload={generatedAt:new Date().toISOString(),courses:[],sources:[]};
t.state.demo=true;
t.renderHeader();
assert.match(t.elements.dataStatus.textContent,/範例資料/);
assert.equal(t.elements.dataWarning.hidden,false);
t.renderSources();
assert.match(t.elements.sourceRows.innerHTML,/尚無來源健康紀錄/);
t.state.payload.sources=[{name:'Source',status:'error',notes:'須人工覆核',lastSuccessAt:'2025-01-01T09:00:00+08:00',courseCount:0}];
t.renderSources();
assert.match(t.elements.sourceRows.innerHTML,/須人工覆核/);
assert.match(t.elements.sourceRows.innerHTML,/本次 0 筆/);
t.state.payload.sources=[{name:'Partial source',status:'partial'}];
t.renderSources();
assert.match(t.elements.sourceRows.innerHTML,/部分取得/);
context.window.APP_CONFIG.apiUrl='data/courses.json';
context.fetch=async url=> {if(url.startsWith('data/')) throw Error('offline');return {ok:true,json:async()=>({schemaVersion:1,courses:[]})};};
t.state.demo=false;
await t.loadPayload();
assert.equal(t.state.demo,true);
console.log('UI display checks passed: dates, unknowns, escaping, links, metrics, sources, demo fallback.');
